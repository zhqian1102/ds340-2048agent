from game2048 import Game2048, encode_board
from dqn import ReplayBuffer
import random

buffer = ReplayBuffer(capacity=1000)

game = Game2048(seed=1)

for i in range(10):
    state = encode_board(game.board)
    action = random.choice(game.legal_actions())
    board, reward, done, info = game.step(action)
    next_state = encode_board(board)
    next_legal = [a in game.legal_actions() for a in range(4)]
    buffer.push(state, action, reward, next_state, done, next_legal)

print("Number of transitions in the buffer:", len(buffer))

for state, action, reward, next_state, done, next_legal in buffer.sample(3):
    print("Action:", action, " Reward:", reward, " Done:", done, " Next Legal:", next_legal)
