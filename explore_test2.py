import random
import torch
from game2048 import Game2048, encode_board
from dqn import QNetwork, ReplayBuffer, optimize

net = QNetwork()

target_net = QNetwork()
target_net.load_state_dict(net.state_dict())

optimizer = torch.optim.Adam(net.parameters(), lr=0.001)

buffer = ReplayBuffer(capacity=10000)
for seed in range(5):
    game = Game2048(seed=seed)
    done = False
    while not done:
        state = encode_board(game.board)
        action = random.choice(game.legal_actions())
        board, reward, done, info = game.step(action)
        next_legal = [a in game.legal_actions() for a in range(4)]
        buffer.push(state, action, reward, encode_board(board), done, next_legal)

print("Number of transitions in the buffer:", len(buffer))

for i in range(200):
    loss = optimize(net, target_net, optimizer, buffer, 32, 0.99)
    if i % 40 == 0:
        print("Number of learning steps:", i, ", Loss:", loss)
